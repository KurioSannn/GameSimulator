"""Regenerates the 'Playable cases' section of research/cases/CASE_REGISTRY.md from the data files,
so the registry can never again list topics the files do not contain. Run after adding cases."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REG = ROOT / "research/cases/CASE_REGISTRY.md"
START = "## Playable cases (generated)"
END = "## Candidate corpus"


def main():
    rows, follow = [], {}
    for p in sorted((ROOT / "game/data/cases").glob("*.json")):
        c = json.loads(p.read_text(encoding="utf-8"))
        if c.get("class") != "major_historical":
            follow.setdefault(c["case_id"].rsplit("-", 1)[0], []).append(c["case_id"])
            continue
        r = json.loads((ROOT / c["research_ref"]).read_text(encoding="utf-8"))
        ep = (ROOT / f"game/data/story/episodes/{c['case_id']}.json").exists()
        rows.append((c["case_id"], r.get("title", c["title"]), c.get("location_label", ""), r.get("category", ""),
                     len(r.get("sources", [])), len(c["choices"]), "ya" if ep else "TIDAK", c["trigger"]["conditions"]["all"][0]["value"]))
    out = [START, "", "Generated by `scripts/story/build_registry.py` from game/data/cases, research/cases and game/data/story/episodes.", "",
           f"**{len(rows)} top-level playable cases** (each: research record with sources read on retrieval, 3 choices, narrative episode, standalone scenario).", "",
           "| ID | Peristiwa (research title) | Lokasi | Domain | Sumber | Pilihan | Episode | Bulan buka | Lanjutan |", "|---|---|---|---|---|---|---|---|---|"]
    for cid, title, loc, cat, ns, nc, ep, tick in rows:
        out.append(f"| {cid} | {title} | {loc} | {cat} | {ns} | {nc} | {ep} | {tick} | {', '.join(follow.get(cid, [])) or '-'} |")
    out.append("")
    s = REG.read_text(encoding="utf-8")
    if START in s:  # replace the previous generated section in place
        i = s.index(START)
        j = s.index("\n## ", i + len(START))
        s = s[:i] + "\n".join(out) + s[j:]
    else:  # first run: insert right after the title paragraph
        k = s.index("\n### ") if "\n### " in s else s.index("\n## ")
        s = s[:k] + "\n\n" + "\n".join(out) + s[k:]
    REG.write_text(s, encoding="utf-8")
    print(f"{len(rows)} playable cases written to registry")


if __name__ == "__main__":
    main()
